import assert from 'node:assert/strict';
import { test } from 'node:test';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { copyFile, cp, glob, mkdir, mkdtemp, readFile, readdir, rename, stat, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { devNull } from 'node:os';
import { randomUUID } from 'node:crypto';
import semver from 'semver';
import { getReleasePlan } from '@changesets/get-release-plan';

const root = fileURLToPath(new URL('../', import.meta.url));
const execute = promisify(execFile);

test('正式Changesets候选、增量候选和转正式版本共用发行准入，未生成版本不能准备产物', async context => {
  await mkdir(join(root, '.tmp'), { recursive: true });
  const directory = await mkdtemp(join(root, '.tmp/release-versioning-'));
  const env = { ...process.env, GIT_AUTHOR_NAME: 'hanger', GIT_COMMITTER_NAME: 'hanger',
    GIT_AUTHOR_EMAIL: '26617816+hanger-source@users.noreply.github.com',
    GIT_COMMITTER_EMAIL: '26617816+hanger-source@users.noreply.github.com', NPM_CONFIG_USERCONFIG: devNull, NPM_CONFIG_OFFLINE: 'true' };
  const run = async (command, args) => (await execute(command, args, { cwd: directory, env, signal: context.signal, maxBuffer: 4 * 1024 * 1024 })).stdout.trim();
  const config = JSON.parse(await readFile(join(root, 'scripts/release.config.json'), 'utf8'));
  const copy = async file => {
    await mkdir(join(directory, file, '..'), { recursive: true });
    await copyFile(join(root, file), join(directory, file));
  };
  for (const file of ['package.json', 'package-lock.json', '.gitignore', 'scripts/release.mjs', 'scripts/release.config.json']) await copy(file);
  await cp(join(root, '.changeset'), join(directory, '.changeset'), { recursive: true });
  await cp(join(root, 'scripts/release'), join(directory, 'scripts/release'), { recursive: true });
  for (const entry of config.packages) {
    await copy(entry.directory + '/package.json');
    await copy(entry.directory + '/CHANGELOG.md');
  }
  await cp(join(root, 'node_modules/@changesets/cli'), join(directory, 'node_modules/@changesets/cli'), { recursive: true });
  const release = join(directory, 'scripts/release.mjs');
  const commit = async label => {
    // 仅提交本测试拥有的临时仓库，不暂存源码工作区或并发改动。
    await run('git', ['add', '--all']);
    await run('git', ['-c', 'commit.gpgsign=false', '-c', 'core.hooksPath=' + devNull, 'commit', '-m', label]);
    return run('git', ['rev-parse', 'HEAD']);
  };
  const currentVersion = async () => JSON.parse(await readFile(join(directory, config.packages[0].directory, 'package.json'), 'utf8')).version;
  const changeset = async type => {
    const file = join(directory, '.changeset', 'versioning-' + randomUUID() + '.md');
    await writeFile(file, `---\n"@hanger-source/dsh-reactive": ${type}\n---\n\n公共能力的待发行变更。\n`);
  };
  const readIfPresent = async file => {
    try { return await readFile(join(directory, file)); }
    catch (error) { if (error.code !== 'ENOENT') throw error; }
  };
  const originals = async () => {
    const files = new Map();
    for await (const file of glob(['.changeset/**/*.md', '.changeset/pre.json'], { cwd: directory }))
      files.set(file, await readFile(join(directory, file)));
    return files;
  };
  const archives = async () => {
    try { return await readdir(join(directory, '.trash')); }
    catch (error) { if (error.code !== 'ENOENT') throw error; return []; }
  };
  const recovery = [];
  const applyVersion = async channel => {
    const before = await originals(), prior = await archives();
    await run(process.execPath, [release, 'version', '--channel', channel]);
    const created = (await archives()).filter(name => !prior.includes(name));
    const consumed = [];
    for (const [file, content] of before) {
      const current = await readIfPresent(file);
      if (current?.equals(content)) continue;
      consumed.push(file);
      assert.equal(created.length, 1, '被版本化修改或消费的原文必须仍可恢复');
      assert.deepEqual(await readFile(join(directory, '.trash', created[0], file)), content, file);
    }
    assert.equal(await run('git', ['tag', '--list']), '', '版本化不创建发行tag');
    if (await run('git', ['status', '--porcelain=v1'])) await commit('version generated by Changesets');
    recovery.push({ channel, archives: created, consumed });
    return created;
  };
  const options = async channel => ({ channel, commit: await run('git', ['rev-parse', 'HEAD']), tag: config.tagPrefix + await currentVersion() });
  await run('git', ['init', '-b', 'main']);
  await commit('copied release workspace');
  await run('git', ['checkout', '--detach']);
  const { releaseSource } = await import(pathToFileURL(join(directory, 'scripts/release/common.mjs')).href);

  await changeset('minor');
  await commit('pending public capability');
  const initial = await options(semver.prerelease(await currentVersion()) ? 'next' : 'stable');
  await assert.rejects(releaseSource(initial), /RELEASE_VERSIONING_REQUIRED/);
  const candidate = join(directory, '.tmp/blocked-candidate');
  await assert.rejects(run(process.execPath, [release, 'prepare', '--channel', initial.channel,
    '--commit', initial.commit, '--tag', initial.tag, '--out', candidate]), error => {
    assert.match(error.stderr, /RELEASE_VERSIONING_REQUIRED/); return true;
  });
  await assert.rejects(stat(candidate), { code: 'ENOENT' });
  assert.equal(await run('git', ['tag', '--list']), '');

  const beforeFailure = await originals(), unchangedVersion = await currentVersion();
  await writeFile(join(directory, '.trash'), '归档路径被文件占用，不能进入版本化。\n');
  await commit('blocked archive destination');
  await assert.rejects(run(process.execPath, [release, 'version', '--channel', 'next']), error => {
    assert.match(error.stderr, /EEXIST|ENOTDIR/u); return true;
  });
  assert.equal(await currentVersion(), unchangedVersion);
  for (const [file, content] of beforeFailure) assert.deepEqual(await readIfPresent(file), content);
  assert.deepEqual(await readIfPresent('.changeset/pre.json'), beforeFailure.get('.changeset/pre.json'),
    '原文归档失败不能先进入预发布状态');
  await mkdir(join(directory, '.tmp'), { recursive: true });
  await rename(join(directory, '.trash'), join(directory, '.tmp/blocked-archive-destination'));
  await commit('restore archive destination');

  await applyVersion('next');
  const firstCandidate = await currentVersion();
  assert.equal(semver.prerelease(firstCandidate)?.[0], 'next');
  assert.equal((await releaseSource(await options('next'))).version, firstCandidate);
  const archived = await getReleasePlan(directory);
  assert.equal(archived.releases.filter(item => item.type !== 'none').length, 0, '已进入候选的Changeset不再阻塞同一候选');
  await run(process.execPath, [release, 'plan', '--out', '.tmp/after-candidate.json']);
  assert.equal(JSON.parse(await readFile(join(directory, '.tmp/after-candidate.json'), 'utf8')).releases.length, 0,
    '生成版本后的完整计划不受落后main分支影响');

  await changeset('patch');
  const pre = join(directory, '.changeset/pre.json');
  await writeFile(pre, JSON.stringify(JSON.parse(await readFile(pre, 'utf8')), null, 4) + '\n\n');
  await commit('pending candidate follow-up');
  await assert.rejects(releaseSource(await options('next')), /RELEASE_VERSIONING_REQUIRED/);
  await applyVersion('next');
  const nextCandidate = await currentVersion();
  assert.ok(semver.gt(nextCandidate, firstCandidate));
  assert.equal((await releaseSource(await options('next'))).version, nextCandidate);

  await applyVersion('stable');
  const stable = await currentVersion();
  assert.equal(semver.prerelease(stable), null);
  assert.equal((await releaseSource(await options('stable'))).version, stable);
  await run(process.execPath, [release, 'plan', '--out', '.tmp/after-stable.json']);
  assert.equal(JSON.parse(await readFile(join(directory, '.tmp/after-stable.json'), 'utf8')).releases.length, 0);
  const beforeNoop = await archives();
  await assert.rejects(run(process.execPath, [release, 'version', '--channel', 'stable']), error => error.code === 1);
  assert.deepEqual(await archives(), beforeNoop, '无待消费Changeset或原预发布状态时不建立归档');
  assert.equal(await currentVersion(), stable);
  assert.equal(await run('git', ['status', '--porcelain=v1']), '');

  const changelog = join(directory, config.packages[0].directory, 'CHANGELOG.md');
  await writeFile(changelog, '## 999.0.0\n\n' + await readFile(changelog, 'utf8'));
  await commit('mismatched changelog head');
  await assert.rejects(releaseSource(await options('stable')), /RELEASE_CHANGELOG_VERSION_REQUIRED/);
  assert.equal(await run('git', ['tag', '--list']), '');
  console.info('release.versioning.workflow', { directory, firstCandidate, nextCandidate, stable, recovery });
});
